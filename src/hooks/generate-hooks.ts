const PRE_FLIGHT_GATE_SCRIPT = `#!/usr/bin/env node
// Generated by clarte - do not edit
import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

if (process.env.CLARTE_HOOKS_DISABLED) process.exit(0);

${PARSE_STDIN}
const tool = input.tool_name;
if (!tool) process.exit(0);

const GATED_TOOLS = new Set(["Read", "Grep", "Glob"]);
const FILE_READ_BASH = /\\b(cat|head|tail)\\s+\\S*\\.(?:ts|js|tsx|jsx|mjs|cjs|py|rs|go|java|rb|c|cpp|h|md)\\b/;

const isGated = GATED_TOOLS.has(tool) ||
  (tool === "Bash" && FILE_READ_BASH.test(input.tool_input?.command || ""));
if (!isGated) process.exit(0);

const cwd = input.cwd || process.cwd();
const TASK_CONTEXT = resolve(cwd, ".clarte/task-context.md");
const DONE_MARKER = resolve(cwd, "${PRE_FLIGHT_DONE}");

// Only gate when task-context.md exists (routing data is available)
if (!existsSync(TASK_CONTEXT)) process.exit(0);
// Gate already passed
if (existsSync(DONE_MARKER)) process.exit(0);

const output = JSON.stringify({
  hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "deny",
    permissionDecisionReason: "Pre-flight gate: spawn the clarte-pre-flight agent before reading any files.\\nCall: Agent(subagent_type=\\"clarte-pre-flight\\", prompt=\\"<task description>\\")\\nIt reads the relevant files and returns exact edit instructions. Apply them directly - no further reads needed.",
  }
});
process.stdout.write(output);
`;

const FAIL_FAST_SCRIPT = `#!/usr/bin/env node
// Generated by clarte - do not edit
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve } from "node:path";

if (process.env.CLARTE_HOOKS_DISABLED) process.exit(0);

${PARSE_STDIN}
const tool = input.tool_name;
if (!tool) process.exit(0);

const cwd = input.cwd || process.cwd();
const STATE_DIR = resolve(cwd, ".clarte/hooks/.state");
const FF_STATE = STATE_DIR + "/fail-fast.json";
const THRESHOLD = 3;
const TEST_RE = /\\b(npm\\s+test|npm\\s+run\\s+test|pnpm\\s+(run\\s+)?test|yarn\\s+test|bun\\s+(run\\s+)?test|npx\\s+(vitest|jest|mocha)|vitest|jest|mocha|pytest|cargo\\s+test|go\\s+test)\\b/;
const debug = process.env.CLARTE_HOOK_DEBUG === "1";

function log(msg) { if (debug) process.stderr.write("[fail-fast] " + msg + "\\n"); }

function readFFState() {
  try { return JSON.parse(readFileSync(FF_STATE, "utf-8")); } catch { return { base: "", count: 0 }; }
}

function writeFFState(state) {
  try { mkdirSync(STATE_DIR, { recursive: true }); writeFileSync(FF_STATE, JSON.stringify(state)); } catch {}
}

function extractBase(cmd) {
  return cmd.split("|")[0].replace(/\\s*2>&1\\s*$/, "").trim();
}

if (tool !== "Bash" && tool !== "Edit" && tool !== "Write") process.exit(0);

if (existsSync(resolve(cwd, ".clarte/fail-fast-override"))) {
  log("override file found, skipping");
  process.exit(0);
}

if (tool === "Edit" || tool === "Write") {
  log("edit/write detected, resetting state");
  writeFFState({ base: "", count: 0 });
  process.exit(0);
}

if (tool === "Bash") {
  const cmd = input.tool_input?.command || "";
  if (TEST_RE.test(cmd)) {
    // Deny background test runs immediately - they spawn TaskOutput polling loops
    // that bypass the fail-fast counter. Force blocking Bash so we can count retries.
    if (input.tool_input?.run_in_background) {
      const output = JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: "Do not run test commands in the background. Run them directly (without run_in_background) so results are available immediately."
        }
      });
      process.stdout.write(output);
      process.exit(0);
    }
    const base = extractBase(cmd);
    const state = readFFState();
    if (state.base === base) {
      state.count += 1;
    } else {
      state.base = base;
      state.count = 1;
    }
    log("test #" + state.count + " base: " + base.slice(0, 80));
    writeFFState(state);
    if (state.count >= THRESHOLD) {
      const output = JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: "Blocked: you have run the same test command " + state.count + " times with no code edits in between. The test output will not change. Re-read the existing output and try a different fix, or create .clarte/fail-fast-override to disable this check."
        }
      });
      process.stdout.write(output);
      process.exit(0);
    }
  }
  // Non-test Bash (grep, cat, git) does NOT reset the counter.
  // Only Edit/Write resets, because the agent actually tried a fix.
}
`;

