interface HookEntry {
  type: string;
  command: string;
}

interface MatchedHookGroup {
  matcher?: string;
  hooks: HookEntry[];
}

interface ClaudeSettings {
  hooks?: {
    PreToolUse?: MatchedHookGroup[];
    PostToolUse?: MatchedHookGroup[];
    SessionStart?: MatchedHookGroup[];
    [key: string]: unknown;
  };
  [key: string]: unknown;
}

function isClartHook(entry: MatchedHookGroup): boolean {
  return entry.hooks?.some((h) => h.command?.includes(`${HOOKS_DIR}/`)) ?? false;
}

function upsertHookEntry(entries: MatchedHookGroup[], newEntry: MatchedHookGroup, hookFile: string): void {
  const existingIdx = entries.findIndex((entry) =>
    entry.hooks?.some((h) => h.command?.endsWith(`${HOOKS_DIR}/${hookFile}`)),
  );
  if (existingIdx >= 0) {
    entries[existingIdx] = newEntry;
  } else {
    entries.push(newEntry);
  }
}

/**
 * Configure Claude Code hook settings in .claude/settings.json.
 * Merges SessionStart and PreToolUse hooks without clobbering user-defined hooks.
 */
export async function configureClaudeHooks(rootDir: string): Promise<void> {
  const settingsPath = path.join(rootDir, SETTINGS_PATH);
  const raw = (await readJsonFile(settingsPath)) as ClaudeSettings | null;
  const settings: ClaudeSettings = raw ?? {};

  if (!settings.hooks) {
    settings.hooks = {};
  }

  // Clean up all existing clarte hooks across all known events (including legacy PostToolUse).
  for (const event of ALL_HOOK_EVENTS) {
    const group = settings.hooks[event] as MatchedHookGroup[] | undefined;
    if (group) {
      settings.hooks[event] = group.filter((entry) => !isClartHook(entry));
    }
  }

  // Insert fresh hooks
  for (const def of HOOK_DEFS) {
    const group = (settings.hooks[def.event] ??= []) as MatchedHookGroup[];
    const entry: MatchedHookGroup = {
      ...(def.matcher ? { matcher: def.matcher } : {}),
      hooks: [{ type: "command", command: `node ${HOOKS_DIR}/${def.file}` }],
    };
    upsertHookEntry(group, entry, def.file);
  }

  await writeFileSafe(settingsPath, JSON.stringify(settings, null, 2) + "\n");
}
